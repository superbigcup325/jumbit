#!/usr/bin/env bash
# Performance scale set: import/query timing and peak memory on a million lines of z-format data (jumbit vs upstream zoxide).
#
# Scenarios (the timing surface):
#   imp    import z                    — lines of input, unique paths rotating (each path repeats 3-4 times,
#                                        triggering the dedup accumulator); about 1% bad rows are reported on stderr
#   qall   query --list --score --all  — full output (the whole load + decode + sort + format + write chain;
#                                        the sort dirties the db, so every round writes the whole file once, on both sides alike)
#   qkw    query src --all             — a keyword matching about 1/10 of the entries in the final component, single-row output
#                                        (dominated by the keyword-matching scan)
#   qtsv   query --tsv --all           — a full output through jumbit's extension channel (no upstream counterpart; recorded only)
#
# Verdict: not "faster than upstream", only "healthy numbers" (same order of magnitude) — the numbers decide whether optimization is worth taking on.
#
# Environment note: the import scenario pins MAXAGE=u32::MAX to hold aging down. The accumulated rank over a million lines is far past
# the default 10000, where the aging factor would shrink every entry below 1 and empty the database, leaving the query scenarios measuring an empty one
# (aging-semantics parity is covered by dataset_check.sh; here the database only needs to survive).
# Aging still fires under u32::MAX (accumulated rank ~5.6e9 > 4.29e9, factor ~0.69): entries whose rank sum
# is too small are purged (about a tenth, trimmed identically on both sides) — the real aging path is part of the measured surface anyway,
# so the entry count running slightly below the unique-path count is expected.
#
# Depends on: zoxide (on PATH), python3, and the jumbit release binary (moon build --release).
# Timing wrapper: scripts/perf_run.py (wall + child peak RSS, no GNU time dependency).
# The data is generated by gen_dataset.py --unique-paths (fixed seed, reproducible) into /tmp, never into the repo.
#
# Usage: bash scripts/perf_check.sh [--quick]
#   --quick  100k lines / 30k unique paths / 1 round (validates the script itself; the numbers do not count)

set -u
cd "$(dirname "$0")/.."

bin=_build/native/release/build/cmd/jumbit/jumbit.exe
lines=1000000 unique=300000 reps=3
if [ "${1:-}" = "--quick" ]; then
  lines=100000 unique=30000 reps=1
fi
maxage=4294967295  # u32::MAX (both sides share the domain: upstream parses it as u32)

need() { command -v "$1" >/dev/null || { echo "✗ missing dependency: $1" >&2; exit 2; }
}
need zoxide
need python3
[ -x "$bin" ] || { echo "✗ $bin is missing (run moon build --release first)" >&2; exit 2; }

tmp=$(mktemp -d /tmp/jumbit-perf-XXXX)
trap 'rm -rf "$tmp"' EXIT

echo "== generating the dataset (z format, $lines lines / $unique unique paths) =="
python3 scripts/gen_dataset.py --format z --lines "$lines" --unique-paths "$unique" \
  --out "$tmp/z.txt"
echo "dataset: $(wc -c < "$tmp/z.txt") bytes"

for r in $(seq 0 $((reps - 1))); do mkdir -p "$tmp/jb-$r" "$tmp/zo-$r"; done

# timed <tag> <cmd...>: the environment comes in via the TIMED_ENV array (--env=KEY=V, with {rep} expanded per round)
timed() {
  local tag="$1"; shift
  python3 scripts/perf_run.py --reps "$reps" ${TIMED_ENV[@]+"${TIMED_ENV[@]}"} \
    --stdout "$tmp/$tag.out" --stderr "$tmp/$tag.err" -- "$@" >"$tmp/$tag.perf"
}

TIMED_ENV=("--env=_JB_DATA_DIR=$tmp/jb-{rep}" "--env=_JB_MAXAGE=$maxage" "--env=_Z_DATA=$tmp/z.txt")
timed imp.jb "$bin" import z
TIMED_ENV=("--env=_ZO_DATA_DIR=$tmp/zo-{rep}" "--env=_ZO_MAXAGE=$maxage" "--env=_Z_DATA=$tmp/z.txt")
timed imp.zo zoxide import z

TIMED_ENV=("--env=_JB_DATA_DIR=$tmp/jb-{rep}")
timed qall.jb "$bin" query --list --score --all
TIMED_ENV=("--env=_ZO_DATA_DIR=$tmp/zo-{rep}")
timed qall.zo zoxide query -l -s -a

TIMED_ENV=("--env=_JB_DATA_DIR=$tmp/jb-{rep}")
timed qkw.jb "$bin" query src --all
TIMED_ENV=("--env=_ZO_DATA_DIR=$tmp/zo-{rep}")
timed qkw.zo zoxide query src -a

TIMED_ENV=("--env=_JB_DATA_DIR=$tmp/jb-{rep}")
timed qtsv.jb "$bin" query --tsv --all

# The --fuzzy fallback path (a jumbit extension; upstream has no fuzzy): a guaranteed-miss keyword triggers it,
# one pass with two exits (before 0.2.0 it was a second whole-database scan + sort with an empty keyword, see BENCHMARKS)
TIMED_ENV=("--env=_JB_DATA_DIR=$tmp/jb-{rep}")
timed qfz.jb "$bin" query zzzznomatch --all --fuzzy

# Summary: best wall per scenario (a lower bound under noise); RSS is that scenario's child peak (ru_maxrss, KB)
row() { # <scenario label> <tag>
  awk '{ if (NR == 1 || $2 < minw) minw = $2; rss = $3; if ($4 != 0) bad = 1 }
        END { printf "%.3f %8.1f   %s\n", minw, rss / 1024, (bad ? "nonzero!" : "0") }' \
    "$tmp/$2.perf" | awk -v name="$1" -v tool="${2##*.}" \
    '{ printf "%-10s %-8s %10s %9s MB  %s\n", name, tool, $1, $2, $3 }'
}

best() { awk '{ if (NR == 1 || $2 < m) m = $2 } END { print m }' "$tmp/$1.perf"; }

echo
echo "== timing (reps=$reps, best wall; RSS = child peak) =="
echo "scenario    tool         wall_s   RSS_MB   exit"
row "import z" imp.jb
row "import z" imp.zo
row "query all" qall.jb
row "query all" qall.zo
row "query kw" qkw.jb
row "query kw" qkw.zo
row "query tsv" qtsv.jb
row "query fuzzy" qfz.jb

jb_n=$(wc -l < "$tmp/qall.jb.out")
zo_n=$(wc -l < "$tmp/qall.zo.out")
echo
echo "database entries (qall output lines): jumbit=$jb_n zoxide=$zo_n (about $unique minus the aging trim)"
echo "import stderr bytes: jb=$(wc -c < "$tmp/imp.jb.err") zo=$(wc -c < "$tmp/imp.zo.err")"
echo "database file bytes: jb=$(wc -c < "$tmp/jb-0/db.txt") zo=$(wc -c < "$tmp/zo-0/db.zo") (zo is binary, do not read it as lines)"

fail=0
if [ "$jb_n" -lt $((unique * 8 / 10)) ] || [ "$zo_n" -lt $((unique * 8 / 10)) ]; then
  echo "✗ entry count far below the unique-path count — did aging purge the database? check MAXAGE" >&2
  fail=1
fi
# The two sides are not required to match: jumbit clamps the rank at the import entry point per [#3] while upstream does not, so under the u32::MAX pin
# edge entries survive differently (measured ~2% apart on 2026-10-05); semantic consistency is guarded by dataset_check.sh's
# boundary-row suite, and this only guards against catastrophic drift (the 80% floor above plus the 5% band)
if [ "$jb_n" -gt $((zo_n * 105 / 100)) ] || [ "$jb_n" -lt $((zo_n * 95 / 100)) ]; then
  echo "✗ the two sides differ by over 5% in entry count (jb=$jb_n zo=$zo_n) — check the aging/clamping semantics" >&2
  fail=1
fi
if [ "$(wc -l < "$tmp/qkw.jb.out")" -ne 1 ] || [ "$(wc -l < "$tmp/qkw.zo.out")" -ne 1 ]; then
  echo "✗ a keyword query should print a single row" >&2
  fail=1
fi

echo
echo "jumbit/zoxide time ratio (best wall; below 1 means jumbit is faster):"
for s in imp qall qkw; do
  printf '  %-5s %.2fx\n' "$s" "$(awk "BEGIN{print $(best "$s.jb") / $(best "$s.zo")}")"
done

if [ "$fail" -ne 0 ]; then
  echo "kept the scratch dir: $tmp"
  trap - EXIT
  exit 1
fi
